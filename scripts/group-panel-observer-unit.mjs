#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { createRequire } from "node:module";
const root = path.resolve(import.meta.dirname, ".."), require = createRequire(path.join(root,"app/manage-ui/package.json"));
const ts = require("typescript"), module = { exports: {} };
const code = ts.transpileModule(fs.readFileSync(path.join(root,"app/manage-ui/src/lib/groupPanelObserver.ts"),"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(code,{module,exports:module.exports,setTimeout,clearTimeout});
const { createGroupPanelObserver } = module.exports;
const gate=()=>{let resolve,reject;const promise=new Promise((yes,no)=>{resolve=yes;reject=no});return{resolve,reject,promise}};
const turn=async()=>{for(let index=0;index<8;index++)await Promise.resolve()};
let time=0, timers=new Map(), timerId=0, visible=true, active=false;
const clock={now:()=>time,random:()=>0.5,setTimer:(fn,delay)=>{const id=++timerId;timers.set(id,{fn,at:time+delay});return id},clearTimer:id=>timers.delete(id),visible:()=>visible,active:()=>active};
const reads=[],commits=[],failures=[];
let current=gate();
const observer=createGroupPanelObserver({...clock,read:initial=>{reads.push(initial);return current.promise},commit:(result,initial)=>commits.push({result,initial}),failed:error=>failures.push(error.message)});
const first=observer.load();
for(let index=0;index<8;index++)observer.invalidate();
assert.equal(reads.length,1,"events share the existing in-flight read");
const next=gate();const old=current;current=next;old.resolve("old snapshot");await turn();
assert.equal(reads.length,2,"one follow-up covers all newer invalidations");
next.resolve("current snapshot");await first;
assert.equal(observer.snapshot().dirtyRevision,observer.snapshot().coveredRevision);
assert.equal(timers.size,0,"successful refresh stops retries");
current=gate();const failed=observer.invalidate();current.reject(Error("temporary offline"));await failed;
assert.equal(failures.at(-1),"temporary offline");assert.equal(timers.size,1,"an idle failure has its own retry");
assert.notEqual(observer.snapshot().dirtyRevision,observer.snapshot().coveredRevision,"failure cannot cover the dirty revision");
current=gate();time=800;const retry=[...timers.values()][0];timers.clear();retry.fn();await turn();
assert.equal(reads.length,4,"failure retries without another notification");current.resolve("recovered");await turn();
assert.equal(timers.size,0);assert.equal(observer.snapshot().lastSuccess,800);
time=22000;visible=false;observer.check();assert.equal(reads.length,4,"hidden idle panel does not poll");
visible=true;current=gate();observer.check();assert.equal(reads.length,5,"silent visible event channel receives low frequency verification");current.resolve("watchdog");await turn();
time=25100;active=true;current=gate();observer.check();assert.equal(reads.length,6,"active work retains bounded observation");
observer.dispose();current.resolve("late old group");await turn();assert.equal(commits.some(row=>row.result==="late old group"),false,"disposed generation cannot commit");assert.equal(timers.size,0);
console.log("PASS group panel observer: coalesced dirty revisions, idle retry, successful stop, visibility, low frequency verification, dispose fence");
