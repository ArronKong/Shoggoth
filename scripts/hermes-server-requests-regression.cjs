#!/usr/bin/env node
"use strict";
const assert = require("node:assert/strict");
const http = require("node:http");
const path = require("node:path");
const { WebSocketServer } = require("ws");
const root = process.env.HERMES_TEST_ROOT || path.join(__dirname, "..");
const { HermesBackend } = require(path.join(root, "app/core/hermes-backend"));
const { HermesGatewaySocket } = require(path.join(root, "app/core/hermes-gateway-rpc"));
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn, label) { for (let i = 0; i < 200; i++) { if (fn()) return; await wait(10); } throw Error(label + " timeout"); }
async function main() {
  const frames = [], peers = [], cases = [], sockets = [], prompts = [], expired = [];
  let resumeRequests = [], onPrompt = null;
  const server = http.createServer((req, res) => { res.setHeader("content-type", "application/json"); res.end(JSON.stringify({ model: "fixture", provider: "fixture" })); });
  const wss = new WebSocketServer({ server });
  const emit = (ws, type, session, payload) => ws.send(JSON.stringify({ jsonrpc: "2.0", method: "event", params: { type, session_id: session, payload } }));
  const request = (ws, id, method, params = {}) => ws.send(JSON.stringify({ jsonrpc: "2.0", id, method, params: { session_id: "rt", ...params } }));
  wss.on("connection", ws => { const peer = { ws, frames: [] }; peers.push(peer);
    ws.on("message", bytes => { const msg = JSON.parse(bytes); frames.push(msg); peer.frames.push(msg); if (!msg.method) return;
      let result = {};
      if (msg.method === "client.capabilities") result = { server_requests: true };
      if (msg.method === "session.create") result = { session_id: "rt", stored_session_id: "stored" };
      if (msg.method === "session.resume") result = { session_id: "rt", resumed: "stored", open_requests: resumeRequests };
      if (msg.method === "prompt.submit") result = { status: "streaming" };
      ws.send(JSON.stringify({ jsonrpc: "2.0", id: msg.id, result }));
      if (msg.method === "prompt.submit") onPrompt?.(ws);
    });
  });
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  const dash = { baseUrl: `http://127.0.0.1:${server.address().port}`, token: "synthetic-fixture-token", proc: null, spawned: false };
  const be = new HermesBackend({ getConfig: () => ({ hermesMode: "local", hermesRemotes: [] }) });
  be.profileById.set("hermes-t", "tp"); be.dashboards.set("tp", dash);
  let sending;
  try {
    const key = await be.createSession("hermes-t");
    assert.equal(frames[0]?.method, "client.capabilities", "advertise before session/prompt admission");
    assert.equal(frames[0]?.params.server_requests, true);
    assert.equal(key, "agent:hermes-t:stored");
    const hooks = { prompt: p => prompts.push(p), promptExpire: p => expired.push(p), final() {}, error() {}, delta() {} };
    onPrompt = ws => request(ws, "srq-000000000001", "approval", { request_id: "queue-a", command: "fixture-command-a", choices: ["once", "deny"] });
    sending = be.sendMessage(key, "fixture only", "fixture-run", hooks, {});
    await until(() => prompts.length === 1, "new protocol approval delivered");
    assert.equal(prompts[0].requestId, "srq-000000000001");
    assert.equal(prompts[0].command, "fixture-command-a");
    const peer = peers.at(-1);
    request(peer.ws, "srq-000000000002", "approval", { request_id: "queue-b", command: "fixture-command-b", choices: ["once", "deny"] });
    await until(() => prompts.length === 2, "second request");
    const beforeObserve = frames.length;
    const observed = [], observedExpired = [], observeController = new AbortController();
    const observing = be.watchSession(key, { prompt: p => observed.push(p), promptExpire: p => observedExpired.push(p) }, { signal: observeController.signal });
    assert.deepEqual(observed.map(p => p.requestId), prompts.map(p => p.requestId));
    assert.deepEqual(be.getPendingChatPrompts(key).map(p => p.runId), ["fixture-run", "fixture-run"]);
    assert.deepEqual(be.getPendingChatPrompts("agent:hermes-other:stored"), []);
    assert.equal(frames.length, beforeObserve, "reload must not send, resume, or negotiate");
    await assert.rejects(be.respondChatPrompt(key, { kind: "approval", choice: "once" }));
    await assert.rejects(be.respondChatPrompt(key, { kind: "approval", requestId: prompts[0].requestId, choice: "always" }));
    await assert.rejects(be.respondChatPrompt(key, { kind: "approval", requestId: prompts[0].requestId, choice: "once", all: true }));
    await be.respondChatPrompt(key, { kind: "approval", requestId: prompts[1].requestId, choice: "deny" });
    await be.respondChatPrompt(key, { kind: "approval", requestId: prompts[0].requestId, choice: "once" });
    await until(() => frames.some(f => f.id === prompts[0].requestId && f.result), "same-ID response");
    assert.deepEqual(frames.filter(f => String(f.id).startsWith("srq-")).map(f => [f.id, f.result?.choice]), [[prompts[1].requestId, "deny"], [prompts[0].requestId, "once"]]);
    assert.equal(frames.some(f => f.method === "approval.respond"), false);
    await assert.rejects(be.respondChatPrompt(key, { kind: "approval", requestId: prompts[0].requestId, choice: "once" }));
    cases.push("advertisement precedes real Backend session/send; simultaneous approvals use exact IDs, once-only responses and allowed choices");

    request(peer.ws, "srq-000000000003", "approval", { choices: ["once", "deny"] });
    await until(() => prompts.length === 3, "cancel candidate");
    emit(peer.ws, "request.cancel", "rt", { id: "srq-000000000003", method: "approval", reason: "timeout" });
    await until(() => expired.some(p => p.requestId === "srq-000000000003"), "cancel delivered");
    await assert.rejects(be.respondChatPrompt(key, { kind: "approval", requestId: "srq-000000000003", choice: "once" }));
    request(peer.ws, "srq-000000000003", "approval", {});
    await wait(20); assert.equal(prompts.length, 3);
    request(peer.ws, "srq-000000000004", "clarify", { questions: [{ qid: "one", question: "first?" }, { qid: "two", question: "second?" }], answers: { one: "locked" } });
    await until(() => prompts.length === 4, "clarify delivered");
    assert.equal(prompts[3].question, "second?");
    await assert.rejects(be.respondChatPrompt(key, { kind: "clarify", requestId: prompts[3].requestId, answers: { one: "overwritten", two: "new" } }));
    await be.respondChatPrompt(key, { kind: "clarify", requestId: prompts[3].requestId, value: "new" });
    await until(() => frames.some(f => f.id === prompts[3].requestId && f.result), "clarify response");
    assert.deepEqual(frames.find(f => f.id === prompts[3].requestId && f.result).result, { answers: { one: "locked", two: "new" } });
    assert.ok(observedExpired.some(p => p.requestId === "srq-000000000003"), "reload observer receives cancellation");
    observeController.abort(); await observing;
    assert.equal(be.gwTurns.get("rt").observers.size, 0);
    assert.equal(frames.filter(f => f.method === "prompt.submit").length, 1);
    cases.push("reload restores all pending prompts and watches cancellations; closing the observer never aborts or resends the turn");
    cases.push("cancel expires only exact request and tombstones stale replay; clarify preserves previously locked answers");

    request(peer.ws, "srq-000000000005", "sudo", {});
    await until(() => prompts.length === 5, "sudo");
    await assert.rejects(be.respondChatPrompt(key, { kind: "secret", requestId: prompts[4].requestId, value: "synthetic" }));
    await be.respondChatPrompt(key, { kind: "sudo", requestId: prompts[4].requestId, value: "synthetic" });
    request(peer.ws, "srq-000000000006", "window.read", {});
    request(peer.ws, "srq-000000000007", "unsupported.fixture", {});
    await until(() => frames.some(f => f.id === "srq-000000000007" && f.error), "unsupported answered");
    assert.equal(frames.find(f => f.id === "srq-000000000006").error.code, 4404);
    assert.equal(frames.find(f => f.id === "srq-000000000007").error.code, -32601);
    cases.push("kind mismatch cannot submit secret; unavailable window/unknown methods return explicit protocol errors without waiting");

    const open = { id: "srq-000000000008", method: "approval", params: { session_id: "rt", command: "still pending", choices: ["once", "deny"] } };
    request(peer.ws, open.id, open.method, open.params);
    await until(() => prompts.length === 6, "before reconnect prompt");
    const sock = be.gwSockets.get("tp"), oldWs = sock._ws;
    resumeRequests = [open]; peer.ws.close();
    await until(() => expired.some(p => p.requestId === open.id), "disconnect expires old card");
    await sock.ensureConnected();
    await until(() => prompts.filter(p => p.requestId === open.id).length === 2, "resume open request restored");
    assert.equal(peers.at(-1).frames[0].method, "client.capabilities");
    assert.equal(frames.filter(f => f.method === "prompt.submit").length, 1);
    sock._handleFrame(JSON.stringify({ jsonrpc: "2.0", id: "srq-000000000009", method: "approval", params: { session_id: "rt" } }), oldWs);
    await wait(20); assert.equal(prompts.some(p => p.requestId === "srq-000000000009"), false);
    be.gwRuntimeByKey.set("foreign", { profile: "other", runtimeId: "foreign-rt", generation: sock.generation });
    await assert.rejects(be.respondChatPrompt("foreign", { kind: "approval", requestId: open.id, choice: "once" }));
    await be.respondChatPrompt(key, { kind: "approval", requestId: open.id, choice: "deny" });
    cases.push("reconnect re-advertises, restores open IDs, expires old cards and never resubmits prompt; retired socket and foreign session cannot answer");
    be.gwTurns.get("rt").selection = { operationId: "unproved-selection" };
    request(peers.at(-1).ws, "srq-000000000011", "approval", { choices: ["once", "deny"] });
    await until(() => peers.at(-1).frames.some(f => f.id === "srq-000000000011" && f.error?.code === -32001), "unproved selected turn rejected");
    assert.ok(!prompts.some(p => p.requestId === "srq-000000000011"));
    delete be.gwTurns.get("rt").selection;
    cases.push("selected-turn requests without dispatch proof fail promptly and cannot borrow ordinary approval authority");
    request(peers.at(-1).ws, "srq-000000000010", "approval", { choices: ["once", "deny"] });
    await until(() => prompts.some(p => p.requestId === "srq-000000000010"), "pending at terminal");
    emit(peers.at(-1).ws, "message.complete", "rt", { text: "fixture done", status: "complete" });
    await sending; sending = null;
    assert.equal(sock._serverRequests.size, 0, "terminal cannot leave approvals for a later turn");
    assert.ok(expired.some(p => p.requestId === "srq-000000000010"));
    await assert.rejects(be.respondChatPrompt(key, { kind: "approval", requestId: open.id, choice: "once" }));

    // No consumer means no capability advertisement (control-only callers).
    const control = new HermesGatewaySocket(dash); sockets.push(control);
    await control.request("config.get", {});
    assert.equal(peers.at(-1).frames[0].method, "config.get");
    cases.push("control-only sockets never advertise unimplemented request handling; terminal turns cannot approve stale cards");
    console.log(JSON.stringify({ status: "PASS", groups: cases.length, cases, boundary: "real Backend + real loopback WebSocket; synthetic gateway, no Provider/account/production data" }));
  } finally {
    await be.stop();
    for (const sock of sockets) sock.close();
    for (const peer of peers) peer.ws.terminate();
    await new Promise(resolve => wss.close(resolve));
    await new Promise(resolve => server.close(resolve));
    if (sending) await sending.catch(() => {});
  }
}
main().catch(error => { console.error(error.stack); process.exitCode = 1; });
