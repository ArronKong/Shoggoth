'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { loadManifest, validatePinnedSource, prepareRuntime } = require('./openclaw-selection-host-patch.cjs');
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
const source = '/opt/homebrew/lib/node_modules/openclaw';
const tmp = fs.realpathSync(fs.mkdtempSync('/private/tmp/openclaw-selection-patch-unit-'));
const { root: artifactRoot, manifest } = loadManifest();
const fixture = path.join(tmp, 'pinned-source');
try {
  validatePinnedSource(source);
  fs.mkdirSync(path.join(fixture, 'dist'), { recursive: true });
  fs.writeFileSync(path.join(fixture, 'package.json'), JSON.stringify({ name: 'openclaw', version: '2026.9.5' }));
  for (const item of [...manifest.files, ...(manifest.dependencies || [])]) fs.copyFileSync(path.join(source, item.path), path.join(fixture, item.path));
  for (const item of manifest.licenseFiles) fs.copyFileSync(path.join(source, item.path), path.join(fixture, item.path));
  const prepared = prepareRuntime({ source: fixture, target: path.join(tmp, 'prepared') });
  for (const item of [...manifest.files, ...manifest.newFiles])
    assert.equal(sha(fs.readFileSync(path.join(prepared.runtime, item.path))), item.afterSha256 || item.sha256);
  assert.throws(() => prepareRuntime({ source: fixture, target: source }), /TARGET_MUST_BE_NEW_PRIVATE_TMP/);
  assert.throws(() => prepareRuntime({ source: fixture, target: path.join(tmp, 'prepared') }), /TARGET_MUST_BE_NEW_PRIVATE_TMP/);
  const licenseTarget = path.join(tmp, 'license-drift-target');
  fs.appendFileSync(path.join(fixture, 'LICENSE'), '\nsource notice drift\n');
  assert.throws(() => prepareRuntime({ source: fixture, target: licenseTarget }), /LICENSE_SOURCE_MISMATCH/);
  assert.equal(fs.existsSync(licenseTarget), false, 'license mismatch must fail before target mutation');
  fs.copyFileSync(path.join(source, 'LICENSE'), path.join(fixture, 'LICENSE'));
  const changed = manifest.files[0];
  fs.appendFileSync(path.join(fixture, changed.path), '\n// source drift\n');
  const mustNotExist = path.join(tmp, 'drift-target');
  assert.throws(() => prepareRuntime({ source: fixture, target: mustNotExist }), /SOURCE_MISMATCH/);
  assert.equal(fs.existsSync(mustNotExist), false, 'source mismatch must fail before any target mutation');
  fs.copyFileSync(path.join(source, changed.path), path.join(fixture, changed.path));
  const dependency = manifest.dependencies[0];
  fs.appendFileSync(path.join(fixture, dependency.path), '\n// dependency drift\n');
  const dependencyTarget = path.join(tmp, 'dependency-drift-target');
  assert.throws(() => prepareRuntime({ source: fixture, target: dependencyTarget }), /DEPENDENCY_MISMATCH/);
  assert.equal(fs.existsSync(dependencyTarget), false, 'dependency mismatch must fail before target mutation');
  fs.copyFileSync(path.join(source, dependency.path), path.join(fixture, dependency.path));
  fs.writeFileSync(path.join(fixture, 'package.json'), JSON.stringify({ name: 'openclaw', version: '2026.9.6' }));
  assert.throws(() => validatePinnedSource(fixture), /VERSION_MISMATCH/);
  fs.writeFileSync(path.join(fixture, 'package.json'), JSON.stringify({ name: 'openclaw', version: '2026.9.5' }));
  const wrongArtifact = path.join(tmp, 'wrong-artifacts');
  fs.cpSync(artifactRoot, wrongArtifact, { recursive: true });
  fs.appendFileSync(path.join(wrongArtifact, manifest.newFiles[0].source), '\n// artifact drift\n');
  assert.throws(() => validatePinnedSource(fixture, wrongArtifact), /ARTIFACT_MISMATCH/);
  const noticeArtifact = path.join(tmp, 'notice-artifacts');
  fs.cpSync(artifactRoot, noticeArtifact, { recursive: true });
  fs.appendFileSync(path.join(noticeArtifact, 'THIRD_PARTY_NOTICES.md'), '\nartifact notice drift\n');
  const noticeTarget = path.join(tmp, 'notice-drift-target');
  assert.throws(() => prepareRuntime({ source: fixture, target: noticeTarget, artifactRoot: noticeArtifact }), /LICENSE_ARTIFACT_MISMATCH/);
  assert.equal(fs.existsSync(noticeTarget), false, 'notice artifact mismatch must fail before target mutation');
  validatePinnedSource(source);
  console.log('OpenClaw selection patch unit passed: exact source/output hashes, source/dependency/license/version/artifact rejection before mutation, installed/existing target refusal, global runtime unchanged');
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }
