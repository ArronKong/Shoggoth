"use strict";
const { app, BrowserWindow } = require("electron");
const fs = require("node:fs"), path = require("node:path"), assert = require("node:assert/strict");
const [html, output] = process.argv.slice(2);
app.setPath("userData", path.join(path.dirname(html), "profile"));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1360, height: 1000, webPreferences: { backgroundThrottling: false } });
  const run = js => win.webContents.executeJavaScript(js);
  const wait = async js => { for (let i=0;i<200;i++) { if (await run(js)) return; await new Promise(r=>setTimeout(r,20)); } throw Error("Timed out: "+js); };
  const click = text => run("(()=>{const button=[...document.querySelectorAll('button')].find(b=>b.textContent.includes("+JSON.stringify(text)+")); if(!button)throw Error('Missing button');button.click()})()");
  const shot = async name => { await run("new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(()=>r(true))))");
    await new Promise(resolve => setTimeout(resolve, 100));
    fs.writeFileSync(path.join(output,name),(await win.webContents.capturePage()).toPNG()); };
  let ok = false;
  try {
    await win.loadFile(html); await wait("!!document.querySelector('[data-heartbeat-settings]')");
    assert.equal(await run("window.heartbeatFixture.calls.some(c=>c.method.endsWith('.set'))"),false);
    assert.equal(await run("document.querySelector('[role=switch]').getAttribute('aria-checked')"), "true");
    assert.equal(await run("document.querySelector('input[max=\"10000000\"]').value"), "10000000");
    assert.equal(await run("document.querySelector('input[readonly]').value===Intl.DateTimeFormat().resolvedOptions().timeZone"), true);
    assert.deepEqual(await run("[...document.querySelectorAll('input[type=time]')].map(input=>input.value)"), ["08:00", "22:00"]);
    assert.equal(await run("[...document.querySelectorAll('button')].find(button=>button.textContent.includes('保存检查设置')).disabled"), false);
    await shot("heartbeat-zh-wide.png");
    await run("document.querySelector('[role=switch]').click()"); await click("保存检查设置");
    await wait("window.heartbeatFixture.calls.some(c=>c.method==='proactive.monitor.set')");
    const saved = await run("window.heartbeatFixture.calls.find(c=>c.method==='proactive.monitor.set')");
    assert.equal(saved.params.expectedRevision,2); assert.equal(saved.params.config.enabled,false); assert.ok(saved.params.operationId);
    assert.equal(saved.params.config.timezone,"system"); assert.equal(saved.params.config.budget.maxTokensPerDay,10000000);
    await run("document.querySelector('[role=switch]').click()"); await click("保存检查设置");
    await wait("window.heartbeatFixture.calls.filter(c=>c.method==='proactive.monitor.set').length===2");
    assert.equal(await run("window.heartbeatFixture.calls.filter(c=>c.method==='proactive.monitor.set')[1].params.config.enabled"),true);
    await run("document.querySelectorAll('[role=switch]')[1].click()");
    await wait("document.querySelectorAll('input[type=time]').length===0");
    await run("document.querySelectorAll('[role=switch]')[1].click()");
    await wait("document.querySelectorAll('input[type=time]').length===2");
    assert.deepEqual(await run("[...document.querySelectorAll('input[type=time]')].map(input=>input.value)"),["08:00","22:00"]);
    const setTokens = value => run("(()=>{const input=document.querySelector('input[max=\"10000000\"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,"+value+");input.dispatchEvent(new Event('input',{bubbles:true}))})()");
    await setTokens(10000001);
    await wait("[...document.querySelectorAll('button')].find(button=>button.textContent.includes('保存检查设置')).disabled");
    await setTokens(10000000);
    await wait("![...document.querySelectorAll('button')].find(button=>button.textContent.includes('保存检查设置')).disabled");
    await run("document.querySelector('details').open=true"); await click("清空检查笔记");
    await wait("document.querySelector('pre').textContent.includes('暂无检查笔记')");
    const cleared = await run("window.heartbeatFixture.calls.find(c=>c.method==='proactive.scratch.set')");
    assert.equal(cleared.params.expectedRevision,3); assert.equal(cleared.params.content,"");
    await run("window.heartbeatFixture.failNext=true"); await click("保存检查设置");
    await wait("!!document.querySelector('[role=alert]')"); assert.match(await run("document.querySelector('[role=alert]').textContent"),/PROACTIVE_REVISION_CONFLICT/);
    win.setContentSize(700,850); await new Promise(r=>setTimeout(r,80));
    assert.equal(await run("document.documentElement.scrollWidth<=window.innerWidth+1"),true);
    assert.equal(await run("document.querySelector('textarea').getBoundingClientRect().height>=200"),true);
    await shot("heartbeat-zh-narrow.png");
    await run("window.heartbeatFixture.i18n.changeLanguage('en');document.documentElement.style.colorScheme='dark'");
    await wait("document.body.textContent.includes('Save check settings')");
    await shot("heartbeat-en-dark.png");
    assert.equal(await run("window.fixtureError||null"),null);
    console.log(JSON.stringify({ verified:true, defaults:true, systemTimezone:true, tokenBudgetBoundary:true, activeHoursReset:true, settingsRevision:true, explicitEnable:true, scratchClear:true, conflictVisible:true, narrow:true, locales:["zh-CN","en"] }));
    ok = true;
  } catch(error) { console.error(error.stack); console.error(await run("JSON.stringify({text:document.body.textContent,error:window.fixtureError})").catch(()=>"renderer unavailable")); }
  finally { win.destroy(); app.exit(ok?0:1); }
});
