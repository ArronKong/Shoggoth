// Vite owns the editable UI checkout. The API upstream may be a packaged app
// whose source is read-only, or a different checkout altogether.
import fs from "node:fs";
import path from "node:path";
import { randomUUID } from "node:crypto";
import type { IncomingMessage, ServerResponse } from "node:http";
import type { Plugin } from "vite";

const ENDPOINT = "/__api/debug/overrides";
const MAX_BYTES = 128 * 1024;
const BANNER = "/* Auto-generated by the in-app debug inspector (设置 → 调试 → 保存到源码).\n"
  + "   Staging area: fold these into the real source rules, then delete them here. */\n\n";
type Overrides = Map<string, Map<string, string>>;

class RequestError extends Error {
  status: number;
  constructor(status: number, message: string) { super(message); this.status = status; }
}

function sourceFile(root: string): string | null {
  try {
    const dir = path.join(fs.realpathSync(root), "src");
    if (dir.includes(".asar") || fs.realpathSync(dir) !== dir) return null;
    fs.accessSync(dir, fs.constants.W_OK);
    const file = path.join(dir, "debug-overrides.css");
    try {
      const stat = fs.lstatSync(file);
      if (!stat.isFile() || stat.nlink !== 1 || stat.size > MAX_BYTES) return null;
      fs.accessSync(file, fs.constants.W_OK);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") return null;
    }
    return file;
  } catch { return null; }
}

function trustedRequest(req: IncomingMessage): boolean {
  const address = req.socket.remoteAddress;
  if (address !== "127.0.0.1" && address !== "::1" && address !== "::ffff:127.0.0.1") return false;
  const expectedHost = `127.0.0.1:${req.socket.localPort}`;
  if (req.headers.host !== expectedHost || req.headers["sec-fetch-site"] === "cross-site") return false;
  // This route is handled before the Vite proxy, so browser writes really are
  // same-origin. Local CLI clients have no Origin and still require JSON.
  return req.headers.origin === undefined || req.headers.origin === `http://${expectedHost}`;
}

function readJson(req: IncomingMessage): Promise<unknown> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    let size = 0, failed = false;
    req.on("data", (chunk: Buffer) => {
      if (failed) return;
      size += chunk.length;
      if (size > MAX_BYTES) {
        failed = true;
        reject(new RequestError(413, "style adjustments are too large"));
      } else chunks.push(chunk);
    });
    req.on("error", reject);
    req.on("end", () => {
      if (failed) return;
      try { resolve(JSON.parse(Buffer.concat(chunks).toString("utf8"))); }
      catch { reject(new RequestError(400, "invalid JSON")); }
    });
  });
}

function record(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function incomingOverrides(body: unknown): Overrides {
  if (!record(body) || !record(body.overrides)) throw new RequestError(400, "missing overrides");
  const result: Overrides = new Map();
  for (const [selector, props] of Object.entries(body.overrides)) {
    if (!selector.trim() || /[{};@\r\n]|\/\*/.test(selector) || !record(props)) {
      throw new RequestError(400, "invalid style selector or declarations");
    }
    const declarations = new Map<string, string>();
    for (const [prop, value] of Object.entries(props)) {
      if (!/^(?:--[\w-]+|-?[a-zA-Z][\w-]*)$/.test(prop) || typeof value !== "string"
        || !value.trim() || /[{};\r\n]|\/\*/.test(value)) {
        throw new RequestError(400, "invalid style declaration");
      }
      declarations.set(prop, value.trim());
    }
    if (declarations.size) result.set(selector.trim(), declarations);
  }
  return result;
}

// The staging file uses flat rules. Refuse an unfamiliar format instead of
// partially parsing and overwriting user-authored CSS (e.g. nested @media).
function parseExisting(text: string): Overrides {
  const result: Overrides = new Map();
  let rest = text.replace(/\/\*[\s\S]*?\*\//g, "").trim();
  while (rest) {
    const rule = /^([^{}]+)\{([^{}]*)\}/.exec(rest);
    if (!rule || /@/.test(rule[1])) throw new RequestError(409, "debug-overrides.css contains unsupported CSS; preserve it and fold it into source first");
    const declarations = result.get(rule[1].trim()) || new Map<string, string>();
    let body = rule[2].trim();
    while (body) {
      const decl = /^([\w-]+)\s*:\s*([^;]+);/.exec(body);
      if (!decl) throw new RequestError(409, "debug-overrides.css contains unsupported declarations");
      declarations.set(decl[1], decl[2].trim());
      body = body.slice(decl[0].length).trim();
    }
    result.set(rule[1].trim(), declarations);
    rest = rest.slice(rule[0].length).trim();
  }
  return result;
}

function persist(file: string, incoming: Overrides): number {
  let previous = "";
  try { previous = fs.readFileSync(file, "utf8"); }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
  const merged = parseExisting(previous);
  for (const [selector, props] of incoming) {
    const declarations = merged.get(selector) || new Map<string, string>();
    for (const [prop, value] of props) declarations.set(prop, value);
    merged.set(selector, declarations);
  }
  const css = BANNER + [...merged].map(([selector, props]) =>
    `${selector} {\n${[...props].map(([prop, value]) => `  ${prop}: ${value};\n`).join("")}}\n`).join("");
  if (Buffer.byteLength(css) > MAX_BYTES) throw new RequestError(413, "saved style adjustments are too large");
  const temporary = `${file}.${randomUUID()}.tmp`;
  try {
    fs.writeFileSync(temporary, css, { flag: "wx" });
    fs.renameSync(temporary, file);
  } finally { fs.rmSync(temporary, { force: true }); }
  return merged.size;
}

function json(res: ServerResponse, status: number, body: unknown): void {
  res.writeHead(status, { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" });
  res.end(JSON.stringify(body));
}

export function debugInspectorSource(): Plugin {
  return {
    name: "shoggoth-debug-inspector-source",
    apply: "serve",
    configureServer(server) {
      // A normal configureServer hook runs before Vite's API proxy middleware.
      server.middlewares.use(async (req, res, next) => {
        if (req.url?.split("?")[0] !== ENDPOINT) return next();
        try {
          if (!trustedRequest(req)) throw new RequestError(403, "inspector source writes require the local Vite origin");
          const file = sourceFile(server.config.root);
          if (req.method === "GET") return json(res, 200, { canSave: file !== null });
          if (req.method !== "PUT") throw new RequestError(405, "method not allowed");
          if (!file) throw new RequestError(400, "source not available");
          if (req.headers["content-type"]?.split(";")[0].trim().toLowerCase() !== "application/json") {
            throw new RequestError(415, "application/json required");
          }
          const incoming = incomingOverrides(await readJson(req));
          // Recheck after reading the request; a source file may have changed.
          if (sourceFile(server.config.root) !== file) throw new RequestError(400, "source no longer available");
          return json(res, 200, { ok: true, path: file, selectors: persist(file, incoming) });
        } catch (error) {
          json(res, error instanceof RequestError ? error.status : 500,
            { error: error instanceof Error ? error.message : "unable to save style adjustments" });
        }
      });
    },
  };
}
