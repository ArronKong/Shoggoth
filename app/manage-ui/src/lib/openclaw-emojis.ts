function split(list: string): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const emoji of list.split(/\s+/)) {
    if (!emoji || seen.has(emoji)) continue;
    seen.add(emoji);
    out.push(emoji);
  }
  return out;
}
