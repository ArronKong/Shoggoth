const RUNTIME_LABELS = {
  codex: "Codex", "claude-code": "Claude Code", "grok-build": "Grok Build",
  pi: "Pi", antigravity: "Antigravity", "deepseek-harness": "DeepSeek Harness",
};
const CLIENT_COMMANDS = new Set(["new", "clear", "model", "rename", "name", "copy", "help"]);

function cliReferenceCommands(runtime) {
  return normalizeRuntimeCommands((CLI_COMMAND_ROWS[runtime] || []).map(([name, description, args, aliases]) => ({
    name, description, args, aliases: aliases || [],
    source: `${RUNTIME_LABELS[runtime]} CLI`,
    execution: CLIENT_COMMANDS.has(name) ? "client" : "cli",
  })));
}

function mergeNativeCommands(runtime, live = [], reference = cliReferenceCommands(runtime)) {
  const dynamic = normalizeRuntimeCommands(live.map((command) => ({
    ...command, source: command.source || `${RUNTIME_LABELS[runtime]} runtime`,
    execution: command.execution || (CLIENT_COMMANDS.has(command.name) ? "client" : "runtime"),
  })));
  // An alias in the authoritative catalog must not be stolen by a fallback name.
  const claimed = new Set(dynamic.flatMap((command) => [command.name, ...command.aliases]));
  const fallback = reference.filter((command) => !claimed.has(command.name)).map((command) => ({
    ...command, aliases: command.aliases.filter((alias) => !claimed.has(alias)),
  }));
  return normalizeRuntimeCommands([...dynamic, ...fallback]);
}

function requireRuntimeCommand(text, commands, runtime) {
  const parsed = parseRuntimeCommand(text, commands);
  if (!parsed) throw serviceError("RUNTIME_COMMAND_NOT_FOUND", `${RUNTIME_LABELS[runtime]} command is not available`);
  if (parsed.command.execution === "cli") {
    throw serviceError("RUNTIME_COMMAND_CLI_ONLY", `/${parsed.command.name} requires the ${RUNTIME_LABELS[runtime]} terminal interface. It was not sent to the model.`);
  }
  if (parsed.command.execution === "client") {
    throw serviceError("RUNTIME_COMMAND_CLIENT_REQUIRED", `/${parsed.command.name} must be handled by the Shoggoth conversation UI`);
  }
  return parsed;
}

module.exports = { cliReferenceCommands, mergeNativeCommands, requireRuntimeCommand };
